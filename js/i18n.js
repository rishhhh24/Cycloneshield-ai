class I18nManager {
    constructor() {
        this.currentLang = localStorage.getItem('cycloneshield_lang') || 'en';
    }

    setLanguage(langCode) {
        if (!I18N_DICTIONARY[langCode]) langCode = 'en';
        this.currentLang = langCode;
        localStorage.setItem('cycloneshield_lang', langCode);
        this.applyTranslations();
    }

    t(key) {
        const dict = I18N_DICTIONARY[this.currentLang] || I18N_DICTIONARY['en'];
        return dict[key] || I18N_DICTIONARY['en'][key] || key;
    }

    getLangName() {
        const names = {
            en: "English",
            hi: "हिंदी (Hindi)",
            or: "ଓଡ଼ିଆ (Odia)",
            bn: "বাংলা (Bengali)",
            ta: "தமிழ் (Tamil)",
            te: "తెలుగు (Telugu)",
            mr: "मराठी (Marathi)",
            gu: "ગુજરાતી (Gujarati)"
        };
        return names[this.currentLang] || "English";
    }

    applyTranslations() {
        console.log(`[i18n] Applying language: ${this.currentLang}`);

        // Update elements with data-i18n attributes
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (key) {
                const translation = this.t(key);
                if (el.tagName === 'INPUT' && el.type === 'text') {
                    el.placeholder = translation;
                } else {
                    el.textContent = translation;
                }
            }
        });

        // Update placeholders
        const searchInput = document.getElementById('location-search-input');
        if (searchInput) searchInput.placeholder = this.t('search_placeholder');

        const chatInput = document.getElementById('chat-input');
        if (chatInput) chatInput.placeholder = this.t('chat_placeholder');
    }
}

window.i18n = new I18nManager();
